const {chromium}=require('playwright');
const {spawn}=require('node:child_process');
const fs=require('node:fs'),path=require('node:path'),net=require('node:net'),assert=require('node:assert/strict');
(async()=>{
 const root=path.resolve(__dirname,'..'),out=path.join(root,'artifacts/screenshots/schedule-fix-20261029');
 fs.mkdirSync(out,{recursive:true});
 const sock=net.createServer();await new Promise(r=>sock.listen(0,'127.0.0.1',r));
 const port=sock.address().port;await new Promise(r=>sock.close(r));
 const server=spawn(path.join(root,'.venv/Scripts/python.exe'),[path.join(__dirname,'scheduled-auth-fixture.py'),String(port),path.join(root,'data','schedule-ui-'+Date.now())],{cwd:root,windowsHide:true,stdio:'ignore'});
 let browser;
 const base=`http://127.0.0.1:${port}`,errors=[],checks=[];
 try{
  let ready=false;
  for(let i=0;i<80;i++){try{if((await fetch(base+'/api/health')).ok){ready=true;break;}}catch{}await new Promise(r=>setTimeout(r,150));}
  assert(ready,'Fixture server did not start');
  browser=await chromium.launch({executablePath:'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe',headless:true});
  const ctx=await browser.newContext({viewport:{width:1440,height:1000}}),page=await ctx.newPage();
  page.on('pageerror',e=>errors.push(String(e)));
  const login=await ctx.request.post(base+'/api/session',{data:{username:'alice',password:'tracebank-demo'}});
  assert(login.ok());const csrf=(await login.json()).csrf_token;
  const get=async u=>{const r=await ctx.request.get(base+u);assert(r.ok(),await r.text());return r.json();};
  const post=async(u,data={})=>{const r=await ctx.request.post(base+u,{data,headers:{'X-CSRF-Token':csrf}});assert(r.ok(),await r.text());return r.json();};
  let overview=await get('/api/overview');
  assert.equal(overview.daily_transfer_cents,30000);
  assert.equal(overview.schedules[0].status,'awaiting_verification');
  const op=overview.scheduled_operations[0];assert.equal(op.risk,'red');
  const initialBalance=overview.accounts[0].balance_cents;
  checks.push('Due 1000 remains unpaid after manual 300; persisted red operation exposed');
  await page.goto(base+'/#planner');
  await page.getByRole('button',{name:'前往审批中心验证',exact:true}).waitFor();
  await page.screenshot({path:path.join(out,'01-pending-planner.png'),fullPage:true});
  await page.getByRole('button',{name:'前往审批中心验证',exact:true}).click();
  await page.getByRole('heading',{name:'到期预约转账',exact:true}).waitFor();
  await page.screenshot({path:path.join(out,'02-approval.png'),fullPage:true});
  const panel=page.locator('.approval-item').filter({has:page.getByRole('heading',{name:'到期预约转账'})});
  await panel.getByRole('button',{name:/验证/}).click();
  await page.getByRole('dialog').waitFor();
  const inbox=await get('/api/auth/demo-inbox');
  const code=inbox.messages.find(m=>m.operation_id===op.id).code;
  const dialog=page.getByRole('dialog');
  await dialog.locator('input').first().fill(code);
  await dialog.getByRole('button',{name:/验证|确认/}).last().click();
  await page.waitForFunction(()=>!document.querySelector('[role="dialog"]'));
  overview=await get('/api/overview');
  assert.equal(overview.daily_transfer_cents,130000);
  assert.equal(overview.accounts[0].balance_cents,initialBalance-100000);
  assert.equal(overview.schedules[0].status,'done');
  checks.push('UI verification succeeds without an Agent plan; one debit and exact daily total');
  await page.reload();await page.getByRole('heading',{name:'审批中心',exact:true}).waitFor();
  await page.screenshot({path:path.join(out,'03-completed-approvals.png'),fullPage:true});
  const response=await post('/api/chat',{message:'明天给李娜转1000元'});
  const creation=response.plan.nodes.find(n=>n.operation).operation;
  const created=await post('/api/operations/'+creation.id+'/authorize',{approve:true});
  const sid=created.operation.receipt.schedule_id;
  const forced=await post('/api/schedules/'+sid+'/run-now');
  assert.equal(forced.status,'awaiting_verification');
  await page.reload();
  const nextPanel=page.locator('.approval-item').filter({has:page.getByRole('heading',{name:'到期预约转账'})});
  await nextPanel.getByRole('button',{name:/取消/}).click();
  await page.waitForTimeout(400);
  overview=await get('/api/overview');
  assert.equal(overview.schedules.find(s=>s.id===sid).status,'cancelled');
  assert.equal(overview.daily_transfer_cents,130000);
  checks.push('Demo cannot bypass verification; UI cancel updates schedule without payment');
  await page.setViewportSize({width:390,height:844});
  await page.goto(base+'/#planner');
  await page.getByRole('heading',{name:'资金日程',exact:true}).waitFor();
  assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1),'Mobile horizontal overflow');
  await page.screenshot({path:path.join(out,'04-mobile-planner.png'),fullPage:true});
  checks.push('390px planner renders without horizontal overflow');
  assert.deepEqual(errors,[]);
  fs.writeFileSync(path.join(root,'evals/results/schedule-ui-20261029.json'),JSON.stringify({date:'2026-10-29',mode:'offline',isolated:true,checks,page_errors:errors},null,2)+'\n');
  console.log(JSON.stringify({passed:true,checks:checks.length,page_errors:errors.length}));
 }finally{if(browser)await browser.close();server.kill();}
})().catch(e=>{console.error(e);process.exitCode=1;});
